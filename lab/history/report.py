"""The coverage report: what the dataset holds, season by season, and what it lacks.

Written from the built database alone, so it always describes the dataset as
it is. Every number here is a count of rows; nothing is estimated.
"""

from __future__ import annotations

import datetime as dt
import json
import sqlite3
from collections import Counter
from pathlib import Path

#: The tiers a record can reach, each needing everything before it.
TIERS = (
    ("final", "result is final"),
    ("cutoff", "+ cutoff time known"),
    ("spread", "+ verified spread at the cutoff"),
    ("models", "+ model forecasts available at the cutoff"),
    ("pool", "+ pool line status known (lined or straight up)"),
    ("rules", "+ pool rules evidenced for that week"),
)


def _when(at: float | None) -> str:
    return "—" if at is None else dt.datetime.fromtimestamp(at, dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _table(head: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return out


def tiers(conn: sqlite3.Connection, kind: str) -> dict[int, list[int]]:
    """season -> [games, then the count reaching each tier], for one cutoff kind."""
    out: dict[int, list[int]] = {}
    rows = conn.execute(
        "SELECT r.season, o.game_id IS NOT NULL, r.cutoff_at IS NOT NULL, r.spread_home IS NOT NULL, "
        "r.n_models > 0, r.pool_line_status IN ('lined', 'straight_up'), r.rules_verified "
        "FROM prediction_records r LEFT JOIN outcomes o USING (game_id) WHERE r.cutoff_kind = ?",
        (kind,)).fetchall()
    for season, *checks in rows:
        tally = out.setdefault(season, [0] * (len(TIERS) + 1))
        tally[0] += 1
        for i, _ in enumerate(TIERS):
            if all(checks[: i + 1]):
                tally[i + 1] += 1
    return out


def build_lines(conn: sqlite3.Connection) -> list[str]:
    q = lambda sql, *a: conn.execute(sql, a).fetchall()  # noqa: E731
    one = lambda sql, *a: conn.execute(sql, a).fetchone()[0]  # noqa: E731
    lines = [
        "# Coverage report: Deadeye historical dataset",
        "",
        "Generated by `python -m lab.history.build report` from `lab/data/history.db`.",
        "Counts only; nothing is estimated. Definitions and source limits are in",
        "[`data-audit.md`](data-audit.md).",
        "",
        "## Sources",
        "",
    ]
    lines += _table(
        ["source", "kind", "location", "sha256", "retrieved", "retrieval basis"],
        [[s, k, f"`{loc}`", (h or "—")[:12], _when(at), basis] for s, k, loc, h, at, basis in q(
            "SELECT source_id, kind, location, sha256, retrieved_at, retrieved_at_basis "
            "FROM sources ORDER BY source_id")])

    lines += ["", "## Eligible games by season", "",
              "Each column needs everything to its left. A record never holds the result; the "
              "`final` column is joined in here only to count.", ""]
    for kind in ("week_lock", "kickoff"):
        lines += [f"### Cutoff: `{kind}`", ""]
        data = tiers(conn, kind)
        rows = [[season, *data[season]] for season in sorted(data)]
        rows.append(["**all**", *[sum(r[i] for r in rows) for i in range(1, len(TIERS) + 2)]])
        lines += _table(["season", "games", *[t[0] for t in TIERS]], rows)
        lines += [""]
    lines += ["Tier meanings: " + "; ".join(f"`{k}` {v}" for k, v in TIERS) + ".", ""]

    lines += ["## Undated market lines (quarantined in `*_unverified` fields)", ""]
    rows = q("SELECT season, COUNT(*), SUM(spread_home_unverified IS NOT NULL), "
             "SUM(total_unverified IS NOT NULL), SUM(moneyline_home_unverified IS NOT NULL) "
             "FROM prediction_records WHERE cutoff_kind = 'kickoff' GROUP BY season ORDER BY season")
    lines += _table(["season", "games", "spread", "total", "moneyline"], [list(r) for r in rows])
    lines += ["", "These carry no time, so they may postdate any cutoff. A backtest that uses them has "
              "to say so; `asof.production_forecast` refuses them unless `allow_unverified=True`.", ""]

    lines += ["## Verified time-stamped inputs", ""]
    rows = q("SELECT g.season, g.week, o.source_id, o.timing, COUNT(*), MIN(o.available_at), "
             "MAX(o.available_at) FROM odds_snapshots o JOIN games g USING (game_id) "
             "WHERE o.available_at IS NOT NULL GROUP BY 1, 2, 3, 4 ORDER BY 1, 2, 3, 4")
    lines += _table(["season", "week", "source", "timing", "snapshots", "first available", "last available"],
                    [[s, w, src, t, n, _when(a), _when(b)] for s, w, src, t, n, a, b in rows])
    lines += [""]
    rows = q("SELECT g.season, g.week, f.source_id, COUNT(DISTINCT f.game_id), COUNT(DISTINCT f.model), "
             "COUNT(*), MIN(f.available_at), SUM(f.published_at IS NULL) FROM model_forecasts f "
             "JOIN games g USING (game_id) GROUP BY 1, 2, 3 ORDER BY 1, 2, 3")
    lines += _table(["season", "week", "forecast file", "games", "models", "forecasts", "available",
                     "no publication time"],
                    [[s, w, src, g, m, n, _when(a), p] for s, w, src, g, m, n, a, p in rows])

    lines += ["", "## Pool sheets", ""]
    rows = q("SELECT s.season, s.week, s.games_on_sheet, s.games_matched, s.season_match, "
             "SUM(l.points IS NOT NULL), SUM(l.problem != '') FROM pool_sheets s "
             "LEFT JOIN pool_lines l USING (sheet_id) GROUP BY s.sheet_id ORDER BY 1, 2")
    lines += _table(["season", "week", "games on sheet", "matched to schedule", "season match",
                     "lined games", "unreadable notes"], [list(r) for r in rows])

    lines += ["", "## Missing fields", "", "Records missing each field, by cutoff kind.", ""]
    fields = ("cutoff_at", "spread_home", "spread_open_home", "total", "moneyline_home",
              "pool_line_home")
    rows = []
    for kind in ("week_lock", "kickoff"):
        total = one("SELECT COUNT(*) FROM prediction_records WHERE cutoff_kind = ?", kind)
        rows.append([kind, total] + [one(f"SELECT COUNT(*) FROM prediction_records WHERE cutoff_kind = ? "
                                         f"AND {f} IS NULL", kind) for f in fields]
                    + [one("SELECT COUNT(*) FROM prediction_records WHERE cutoff_kind = ? AND n_models = 0",
                           kind)])
    lines += _table(["cutoff", "records", *fields, "n_models = 0"], rows)

    lines += ["", "## Duplicates and conflicts", ""]
    dup_games = one("SELECT COUNT(*) FROM (SELECT season, week, MIN(home_code, away_code), "
                    "MAX(home_code, away_code), COUNT(*) c FROM games GROUP BY 1, 2, 3, 4 HAVING c > 1)")
    dup_records = one("SELECT COUNT(*) - COUNT(DISTINCT game_id || '|' || cutoff_kind) FROM prediction_records")
    dup_snaps = one("SELECT COUNT(*) FROM (SELECT game_id, market, source_id, available_at, "
                    "COUNT(DISTINCT home_value) d FROM odds_snapshots WHERE timing != 'file_opening' "
                    "GROUP BY 1, 2, 3, 4 HAVING d > 1)")
    dup_forecasts = one("SELECT COUNT(*) FROM (SELECT game_id, model, source_id, COUNT(*) c "
                        "FROM model_forecasts GROUP BY 1, 2, 3 HAVING c > 1)")
    conflicts = one("SELECT COUNT(*) FROM prediction_records WHERE pool_line_status = 'conflict' "
                    "AND cutoff_kind = 'kickoff'")
    cross = dict(q("SELECT crosscheck, COUNT(*) FROM outcomes GROUP BY crosscheck"))
    lines += _table(["check", "count"], [
        ["same season/week/teams listed more than once in the schedule", dup_games],
        ["duplicate prediction records (game, cutoff)", dup_records],
        ["same game/market/source/time with different values", dup_snaps],
        ["same model twice in one forecast file for a game", dup_forecasts],
        ["games whose pool sheets disagree on the line", conflicts],
        ["final scores agreeing with the repo's scores file", cross.get("agree", 0)],
        ["final scores DISAGREEING with the repo's scores file", cross.get("disagree", 0)],
        ["final scores absent from the repo's scores file", cross.get("absent", 0)],
    ])
    disagree = q("SELECT g.game_id, o.away_score, o.home_score FROM outcomes o JOIN games g USING (game_id) "
                 "WHERE crosscheck = 'disagree' ORDER BY g.game_id")
    if disagree:
        lines += ["", "Disagreeing games (nflverse score shown): " +
                  ", ".join(f"`{g}` {a}-{h}" for g, a, h in disagree[:30])]

    lines += ["", "## Flags", "", "Records carrying each flag, by cutoff kind.", ""]
    counts = {kind: Counter() for kind in ("week_lock", "kickoff")}
    for kind, flags in q("SELECT cutoff_kind, flags FROM prediction_records"):
        counts[kind].update(json.loads(flags))
    names = sorted(set(counts["week_lock"]) | set(counts["kickoff"]))
    lines += _table(["flag", "week_lock", "kickoff"],
                    [[f"`{n}`", counts["week_lock"][n], counts["kickoff"][n]] for n in names])

    lines += ["", "## Pool rules on record", ""]
    lines += _table(["rule", "status", "evidenced from", "description"],
                    [[r, s, f"{fs} week {fw}" if fs else "—", d] for r, s, fs, fw, d in q(
                        "SELECT rule_id, status, verified_from_season, verified_from_week, description "
                        "FROM pool_rules ORDER BY rule_id")])

    notes = [n for (n,) in q("SELECT note FROM build_notes ORDER BY n")]
    lines += ["", "## Build notes", ""]
    lines += [f"- {n}" for n in notes] if notes else ["None."]
    return lines + [""]


def write(db_path: Path, dest: Path) -> None:
    conn = sqlite3.connect(f"{Path(db_path).resolve().as_uri()}?mode=ro", uri=True)
    try:
        text = "\n".join(build_lines(conn))
    finally:
        conn.close()
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8")
