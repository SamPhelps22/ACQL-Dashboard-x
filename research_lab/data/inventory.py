"""Measured coverage of every data source, written to docs/DATA_INVENTORY.md."""

from __future__ import annotations

import pandas as pd

from .. import config
from . import fetch, games as games_mod, pbp
from .store import load_injuries
from ..reports import md


def _ftn_part():
    rows = []
    for y in range(2016, config.CURRENT_SEASON + 1):
        f, p = config.RAW / f"ftn_{y}.csv", config.RAW / f"participation_{y}.csv"
        r = {"season": y}
        if f.exists():
            d = pd.read_csv(f, low_memory=False)
            r["ftn_plays"] = len(d)
            r["ftn_games"] = d["nflverse_game_id"].nunique() if "nflverse_game_id" in d else None
            r["ftn_cols"] = ", ".join(c for c in d.columns if c.startswith("is_") or c.startswith("n_"))[:200]
        if p.exists():
            d = pd.read_csv(p, low_memory=False)
            r["part_plays"] = len(d)
            for c in ("offense_personnel", "defense_personnel", "defenders_in_box", "defense_coverage_type",
                      "defense_man_zone_type", "was_pressure", "offense_formation"):
                if c in d:
                    r[f"part_{c}"] = round(float(d[c].notna().mean()), 3)
        rows.append(r)
    return pd.DataFrame(rows)


def table() -> dict:
    g = games_mod.load()
    reg = g[g["game_type"] == "REG"]
    by = reg.groupby("season").agg(games=("game_id", "size"), final=("completed", "sum"),
                                   closing_spread=("spread_line", "count"), moneyline=("home_moneyline", "count"),
                                   total_line=("total_line", "count"), start_qb=("home_qb_id", "count"))
    out = reg[reg["roof"].isin(["outdoors", "open"])]
    by["outdoor"] = out.groupby("season").size()
    by["outdoor_weather"] = out.groupby("season")["temp"].count()
    tg = pbp.load("team_games")
    by["pbp_games"] = tg[tg["game_id"].isin(reg["game_id"])].groupby("season")["game_id"].nunique()
    dr = pbp.load("drives")
    by["drives"] = dr[dr["game_id"].isin(reg["game_id"])].groupby("season").size()
    inj = load_injuries()
    if len(inj):
        by["injury_rows"] = inj.groupby("season").size()
        by["injury_timestamped"] = inj.groupby("season")["date_modified"].apply(lambda s: round(float(s.notna().mean()), 2))
    return {"games": by.fillna(0).astype({c: int for c in by.columns if c != "injury_timestamped"}),
            "charting": _ftn_part()}


def write(path=None) -> str:
    path = path or config.ROOT / "research_lab" / "docs" / "DATA_INVENTORY.md"
    t = table()
    man = fetch.read_manifest()
    lines = ["# Data inventory and coverage", "",
             f"Generated by `python -m research_lab inventory`. Dataset version `{fetch.dataset_version()}` "
             f"(hash of the {len(man)} files' SHA-256 in `data/research_lab/raw/manifest.json`).", "",
             "## Sources and what their timing allows", "",
             "| Source | URL | Fetched (UTC) | Timing status |", "|---|---|---|---|"]
    status = {"games.csv": "schedule known in advance; **closing** lines; **observed** weather; actual starters",
              "pbp": "per play; used only for games completed before the forecast",
              "injuries": "final weekly report; `date_modified` timestamps 2010-2024 only (2009 ~0%, 2025-26 none)",
              "ftn": "charting 2022+ (play action, motion, blitz, box) - Model H feasibility",
              "participation": "personnel / coverage / pressure 2016-2025 (coverage fields partial) - Model H"}
    shown = set()
    for name, e in sorted(man.items()):
        kind = name.split("_")[0].replace(".csv", "") if name != "games.csv" else "games.csv"
        if kind in shown:
            continue
        shown.add(kind)
        n = sum(1 for k in man if k.startswith(kind)) if kind != "games.csv" else 1
        lines.append(f"| {kind} ({n} file{'s' if n > 1 else ''}) | {e['url'].rsplit('/', 1)[0]}/ | {e['fetched_at']} | "
                     f"{status.get(kind, '')} |")
    lines += ["", "## Regular-season coverage by season", "", md.table(t["games"].reset_index(), 2), "",
              "## Charting and participation (Model H)", "", md.table(t["charting"], 3), "",
              "## Not available", "",
              "* **Opening lines, line history, timestamps of odds, cross-book quotes**: not in nflverse; The Odds API "
              "history is a paid product; The Prediction Tracker archive (Deadeye's training source) returns HTTP 403 "
              "(Cloudflare) from this environment.",
              "* **Archived weather forecasts**: Open-Meteo's historical-forecast archive starts in 2022; not fetched. "
              "Weather results are observed-weather upper bounds.",
              "* **Deadeye's logged forecasts** (`data/acql.db`): git-ignored, not in the repository.",
              "* **PFF / Next Gen Stats tracking, coverage charting before 2016**: licensed or unavailable.", ""]
    path.write_text("\n".join(lines))
    return str(path)
