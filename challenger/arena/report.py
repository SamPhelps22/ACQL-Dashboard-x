"""The evaluation report, written from the tables (numbers are never typed in by hand)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from .headtohead import to_markdown


def _labels():
    from .run import LABELS

    return LABELS


def _pair_line(pairs: pd.DataFrame, a: str, b: str, measure: str) -> str:
    r = pairs[(pairs["a"] == a) & (pairs["b"] == b) & (pairs["measure"] == measure)]
    if r.empty:
        return "n/a"
    r = r.iloc[0]
    scale = 100.0 if measure == "accuracy" else 1000.0
    unit = "pct-pts" if measure == "accuracy" else "x1000"
    return (f"{r['mean'] * scale:+.2f} [{r['lo'] * scale:+.2f}, {r['hi'] * scale:+.2f}] {unit} "
            f"({r['games']} games, {r['clusters']} weeks) - {r['verdict']}")


def write_report(out_dir: Path, split: str, summary: dict, t: dict) -> None:
    L = _labels()
    cov = summary["coverage"]
    seasons = summary["seasons"]
    kind = "development" if split == "dev" else "untouched holdout"
    lines = [
        f"# Challenger vs Deadeye - {kind} split ({seasons[0]}-{seasons[-1]})",
        "",
        "Generated by `python -m challenger evaluate --split " + split + "`. Every number below is computed "
        "from stored files; nothing is typed in by hand.",
        "",
        "**This is a retrospective backtest, not a prospective test.** Challenger's forecasts were produced "
        "walk-forward (each season's models fitted only on earlier seasons; features as of each week's "
        "deadline, an hour before the week's first kickoff), but they were generated now, from today's "
        "nflverse data. No Deadeye forecast recorded at the time exists for these seasons: Deadeye is "
        "represented by its own historical proxy and by its pricing curve on the closing line (see "
        "challenger/docs/LIMITATIONS.md).",
        "",
        f"- Challenger run: `{summary['challenger_run']}` (model version `{summary['model_version']}`, "
        f"file SHA-256 `{summary['challenger_file_sha256'][:16]}...`)",
        f"- Regular-season games scheduled in these seasons: {cov['scheduled_games']}; completed: {cov['completed']}; "
        f"ties (left out of probability scores): {cov['ties']}",
        f"- **Matched decided games (every model has a forecast): {cov['matched_decided_games']}**",
        "- Coverage by source: " + ", ".join(f"{k[5:]} {v}" for k, v in cov.items() if k.startswith("with_")),
        "",
        "## 1. Probability quality on the matched games",
        "",
        "Log loss and Brier score are the primary measures (lower is better); accuracy is secondary. "
        "ECE is the expected calibration error over ten probability bins.",
        "",
        to_markdown(t["scores"].assign(model=t["scores"]["model"].map(lambda m: f"{L.get(m, m)} (`{m}`)"))),
        "",
        "### Paired differences (A - B), week-clustered bootstrap 95% intervals",
        "",
        "Negative log-loss / Brier differences mean A is better; positive accuracy differences mean A is better.",
        "",
    ]
    pairs = t["paired"]
    for a, b in (("challenger", "deadeye_proxy"), ("challenger", "deadeye_core_closing"),
                 ("challenger", "market_moneyline"), ("challenger", "market_spread"), ("challenger", "elo"),
                 ("challenger", "logistic"), ("challenger", "boosting"), ("boosting", "logistic"),
                 ("deadeye_proxy", "market_moneyline"), ("deadeye_core_closing", "market_moneyline")):
        lines.append(f"- **{a} vs {b}**")
        for measure in ("log_loss", "brier", "accuracy"):
            lines.append(f"  - {measure}: {_pair_line(pairs, a, b, measure)}")
    lines += ["", "### By season (log loss; Challenger minus Deadeye proxy / market, x1000, 95% CI)", ""]
    sp = t["paired_by_season"].copy()
    if len(sp):
        sp["diff_x1000"] = sp.apply(lambda r: f"{r['mean'] * 1000:+.1f} [{r['lo'] * 1000:+.1f}, {r['hi'] * 1000:+.1f}]", axis=1)
        piv = sp.pivot(index="season", columns="vs", values="diff_x1000").reset_index()
        lines.append(to_markdown(piv))
    bys = t["by_season"].pivot(index="season", columns="model", values="log_loss").reset_index()
    lines += ["", "Log loss by season and model:", "", to_markdown(bys), ""]
    lines += ["## 2. Calibration by probability bucket (home-win probability)", "",
              to_markdown(t["calibration"][t["calibration"]["model"].isin(
                  ["challenger", "deadeye_proxy", "market_moneyline"])]), "",
              "## 3. Favourites, underdogs and probability ranges", "",
              "Each model's own confidence (its favourite's chance):", "", to_markdown(t["by_confidence"]), "",
              "Against the closing-market favourite:", "", to_markdown(t["by_market_side"]), ""]
    if len(t["playoffs"]):
        lines += ["## 4. Playoffs (Deadeye's proxy does not price playoff games)", "",
                  f"Matched decided playoff games: {summary['playoff_coverage'].get('matched_decided_games', 0)}", "",
                  to_markdown(t["playoffs"]), ""]
    if len(t["deadeye_live_2026"]):
        lp = summary.get("live_pair_challenger_vs_deadeye_live") or {}
        lines += ["## 5. Deadeye's full live rule (2026 weeks with Prediction Tracker files)", "",
                  "Retrospective reconstruction through Deadeye's own pricing code with the default 25% model share. "
                  "Weeks 3-5's input files were first committed after that week's first kickoff (week 4's after its "
                  "Sunday games), so this is not a record made at the time. The sample is tiny; it is shown for "
                  "completeness, not for a verdict.", "",
                  f"Matched decided games: {summary['deadeye_live_coverage'].get('matched_decided_games', 0)}", "",
                  to_markdown(t["deadeye_live_2026"]), "",
                  (f"Challenger - Deadeye live, mean log loss difference x1000: {lp['mean'] * 1000:+.1f} over "
                   f"{lp['games']} games in {lp['clusters']} weeks - {lp['verdict']}" if lp else ""), ""]
    if len(t["variants"]):
        lines += ["## 6. Other Challenger variants (separate runs; never mixed into the tables above)", "",
                  "`market_informed` adds the CLOSING spread and moneyline as inputs - information from after the "
                  "ACQL deadline, so it is advantaged. `no_epa` drops every play-by-play feature (an ablation "
                  "against the retrospective EPA-model concern).", "", to_markdown(t["variants"]), ""]
    acq = t["acql_summary"]
    lines += ["## 7. ACQL pool evaluation (actual rules: one point per credited pick, pool lines on 6.5+ favourites)", "",
              f"Weeks scored: {summary['acql']['weeks_scored']}. Pool lines are reconstructed from the closing spread "
              "with the commissioner's measured habit (the same for every model). Opponents' picks are not "
              "reconstructed, so this measures points, not finishing position.", "",
              to_markdown(acq.assign(model=acq["model"].map(lambda m: L.get(m, m))), 3), "",
              "`confidence_points_total` is a standard 1..N confidence pool on straight-up winners - NOT ACQL's "
              "rules - included because the brief asked for it.", "",
              "Points by season:", "", to_markdown(t["acql_by_season"]), "",
              "Within-week rank agreement (Spearman) of home-win chances:", "", to_markdown(t["acql_rank_correlation"], 3), ""]
    if len(t["acql_real_weeks"]):
        lines += ["### Real pick sheets on file (real pool lines, real coaches' picks)", "",
                  "Each model's card scored on the commissioner's real lines, with its place among the real field "
                  "(1 = tied for or holding first). Blank = that model has no forecast for every game that week. "
                  "`deadeye_stored_card` is Deadeye's own stored result for that week from acql/data/pool_weeks.json "
                  "(a replay priced off closing lines, by that file's note), shown where the weeks overlap. "
                  "Eight weeks is far too few to rank anything.", "",
                  to_markdown(t["acql_real_weeks"], 2), ""]
    lines += ["## What this does and does not show", "",
              "- A difference whose interval includes zero is not evidence either way; one hot season is not a verdict.",
              "- The Deadeye proxy is Deadeye's own historical stand-in, not the live engine (market + computer-model "
              "consensus), which cannot be replayed before 2026 here because the Prediction Tracker archives are not "
              "available to this environment.",
              "- Market baselines and `deadeye_core_closing` use closing lines, which post-date the ACQL deadline.",
              "- Challenger's play-by-play EPA comes from today's nflfastR model, fitted on many seasons, including "
              "seasons after the games being predicted - a mild retrospective-data advantage (see the no_epa variant).",
              ""]
    (out_dir / "REPORT.md").write_text("\n".join(lines))
